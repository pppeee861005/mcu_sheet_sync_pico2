def draw_char_16x16(oled, char, x, y, color=1):
    glyph = FONT_16x16.get(char)
    if not glyph:
        oled.rect(x, y, 16, 16, color)
        return
    for row in range(16):
        b1 = glyph[row * 2]
        b2 = glyph[row * 2 + 1]
        for col in range(8):
            if (b1 >> (7 - col)) & 1:
                oled.pixel(x + col, y + row, color)
        for col in range(8):
            if (b2 >> (7 - col)) & 1:
                oled.pixel(x + 8 + col, y + row, color)

def draw_string_cn(oled, text, start_x, start_y, color=1):
    cur_x = start_x
    cur_y = start_y
    for ch in text:
        if ch in FONT_16x16:
            if cur_x + 16 > 128:
                cur_x = start_x
                cur_y += 18
            draw_char_16x16(oled, ch, cur_x, cur_y, color)
            cur_x += 16
        elif ch == '\n':
            cur_x = start_x
            cur_y += 18
        else:
            if cur_x + 8 > 128:
                cur_x = start_x
                cur_y += 18
            oled.text(ch, cur_x, cur_y + 4, color)
            cur_x += 8
